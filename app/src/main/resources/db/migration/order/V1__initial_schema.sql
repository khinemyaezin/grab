-- Order schema is a reserved PostgreSQL identifier and is quoted intentionally.
CREATE TABLE "order".outbox_record (
    attempt_count integer not null,
    event_version integer not null,
    available_at timestamp(6) not null,
    claimed_at timestamp(6),
    id bigint generated by default as identity,
    occurred_at timestamp(6) not null,
    published_at timestamp(6),
    aggregate_id varchar(255) not null,
    aggregate_type varchar(255) not null,
    claim_token varchar(255),
    event_type varchar(255) not null,
    status varchar(255) not null check (status in ('NEW','PROCESSING','PUBLISHED','FAILED')),
    headers oid not null,
    last_error oid,
    payload oid not null,
    primary key (id)
);

CREATE INDEX idx_order_outbox_status_available
    ON "order".outbox_record (status, available_at);
CREATE INDEX idx_order_outbox_claimed_at
    ON "order".outbox_record (claimed_at);
CREATE INDEX idx_order_outbox_aggregate
    ON "order".outbox_record (aggregate_type, aggregate_id);
