-- Fresh canonical workflow schema. Existing legacy workflow databases must be recreated or rebaselined.

CREATE TABLE workflow_execution (
    id varchar(64) not null,
    definition_name varchar(128) not null,
    definition_version integer not null,
    payload_version integer not null,
    caller_scope varchar(128) not null,
    status varchar(32) not null check (status in ('RUNNING','WAITING','COMPENSATING','COMPLETED','FAILED','CANCEL_REQUESTED','CANCELLED','COMPENSATED','NEEDS_ATTENTION')),
    input_json text not null,
    result_json text,
    outputs_json text,
    choices_json text,
    accepted_signals_json text,
    error_message text,
    failure_reason text,
    cancellation_requested boolean not null,
    version bigint not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    primary key (id)
);

CREATE INDEX idx_workflow_execution_status_updated
    ON workflow_execution (status, updated_at);

CREATE TABLE workflow_node_execution (
    execution_id varchar(64) not null,
    node_id varchar(128) not null,
    branch_id varchar(128) not null,
    logical_operation_id varchar(256),
    attempt_id varchar(256),
    phase varchar(32) not null,
    status varchar(32) not null check (status in ('PENDING','ACTIVE','DISPATCHED','RETRY_WAIT','SUCCEEDED','FAILED','SKIPPED','UNKNOWN','COMPENSATING','COMPENSATED')),
    attempts integer not null,
    input_json text,
    output_json text,
    accepted_outcome_json text,
    node_generation bigint not null,
    error_message text,
    deadline_at timestamp(6) with time zone,
    retry_at timestamp(6) with time zone,
    primary key (execution_id, node_id),
    constraint fk_workflow_node_execution
        foreign key (execution_id) references workflow_execution (id)
);

CREATE INDEX idx_workflow_node_retry ON workflow_node_execution (status, retry_at);
CREATE INDEX idx_workflow_node_generation ON workflow_node_execution (execution_id, node_id, node_generation);

CREATE TABLE workflow_signal_receipt (
    transport_message_id varchar(256) not null,
    execution_id varchar(64) not null,
    node_id varchar(128) not null,
    logical_operation_id varchar(256) not null,
    attempt_id varchar(256) not null,
    attempt integer not null,
    phase varchar(32) not null,
    payload_fingerprint varchar(128) not null,
    payload_version integer not null,
    disposition varchar(32) not null check (disposition in ('RECEIVED','PROCESSED','REJECTED')),
    outcome varchar(32) not null check (outcome in ('SUCCEEDED','FAILED','UNKNOWN')),
    received_at timestamp(6) with time zone not null,
    processed_at timestamp(6) with time zone,
    primary key (transport_message_id),
    constraint uq_workflow_signal_operation_fingerprint unique (execution_id, logical_operation_id, payload_fingerprint),
    constraint fk_workflow_signal_execution
        foreign key (execution_id) references workflow_execution (id)
);

CREATE TABLE workflow_timer (
    id bigint generated by default as identity,
    execution_id varchar(64) not null,
    node_id varchar(128) not null,
    node_generation bigint not null,
    logical_operation_id varchar(256) not null,
    phase varchar(32) not null,
    purpose varchar(64) not null,
    due_at timestamp(6) with time zone not null,
    status varchar(32) not null check (status in ('SCHEDULED','CLAIMED','FIRED','CANCELLED')),
    claimed_at timestamp(6) with time zone,
    primary key (id),
    constraint uq_workflow_timer_generation unique (execution_id, node_id, node_generation, purpose, phase),
    constraint fk_workflow_timer_execution
        foreign key (execution_id) references workflow_execution (id)
);

CREATE INDEX idx_workflow_timer_due ON workflow_timer (status, due_at);

CREATE TABLE workflow_history (
    id bigint generated by default as identity,
    execution_id varchar(64) not null,
    sequence_number bigint not null,
    node_id varchar(128),
    event_type varchar(64) not null,
    details_json text,
    occurred_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uq_workflow_history_sequence unique (execution_id, sequence_number),
    constraint fk_workflow_history_execution
        foreign key (execution_id) references workflow_execution (id)
);

CREATE TABLE workflow_start_receipt (
    caller_scope varchar(128) not null,
    idempotency_key varchar(256) not null,
    workflow_name varchar(128) not null,
    definition_version integer not null,
    input_fingerprint varchar(128) not null,
    execution_id varchar(64) not null,
    created_at timestamp(6) with time zone not null,
    primary key (caller_scope, idempotency_key),
    constraint fk_workflow_start_execution
        foreign key (execution_id) references workflow_execution (id)
);

CREATE TABLE workflow_outbox_events (
    id bigint generated by default as identity,
    event_id uuid not null default gen_random_uuid(),
    aggregate_type varchar(255) not null,
    aggregate_id varchar(255) not null,
    event_type varchar(255) not null,
    event_version integer not null,
    status varchar(32) not null check (status in ('NEW','PROCESSING','PUBLISHED','FAILED','DEAD')),
    attempt_count integer not null,
    occurred_at timestamp(6) with time zone not null,
    available_at timestamp(6) with time zone not null,
    claimed_at timestamp(6) with time zone,
    claim_token varchar(255),
    published_at timestamp(6) with time zone,
    headers text not null,
    payload text not null,
    last_error text,
    primary key (id),
    constraint uq_workflow_outbox_event_id unique (event_id)
);

CREATE INDEX idx_workflow_outbox_status_available on workflow_outbox_events (status, available_at);
CREATE INDEX idx_workflow_outbox_claimed_at on workflow_outbox_events (claimed_at);
CREATE INDEX idx_workflow_outbox_aggregate on workflow_outbox_events (aggregate_type, aggregate_id);
CREATE INDEX idx_workflow_outbox_dead on workflow_outbox_events (id) where status = 'DEAD';

CREATE TABLE shedlock (
    name varchar(64) not null,
    lock_until timestamp(3) not null,
    locked_at timestamp(3) not null,
    locked_by varchar(255) not null,
    primary key (name)
);
