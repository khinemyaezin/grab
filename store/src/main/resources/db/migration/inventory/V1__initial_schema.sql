-- Initial PostgreSQL schema for the inventory module.
-- Create-only migration; no seed data.
CREATE TABLE bin (
    active boolean not null,
    max_capacity integer,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    code varchar(255) not null,
    name varchar(255),
    uuid varchar(255) not null unique,
    zone_id varchar(255) not null,
    primary key (id),
    constraint idx_bin_code_zone unique (code, zone_id)
);

CREATE TABLE inventory_item (
    damaged integer not null,
    in_transit integer not null,
    max_stock integer,
    on_hand integer not null,
    reorder_point integer not null,
    reorder_quantity integer not null,
    reserved integer not null,
    safety_stock integer not null,
    id bigint generated by default as identity,
    last_updated timestamp(6) not null,
    version bigint,
    location_id varchar(255) not null,
    merchant_id varchar(255) not null,
    product_variant_id varchar(255),
    sku varchar(255) not null,
    status varchar(255) not null check (status in ('ACTIVE','DISCONTINUED','OUT_OF_STOCK','SUSPENDED')),
    uuid varchar(255) not null unique,
    primary key (id),
    constraint idx_inventory_sku_location unique (sku, location_id)
);

CREATE TABLE inventory_outbox_event (
    attempt_count integer not null,
    event_version integer not null,
    available_at timestamp(6) not null,
    claimed_at timestamp(6),
    id bigint generated by default as identity,
    occurred_at timestamp(6) not null,
    published_at timestamp(6),
    aggregate_id varchar(255) not null,
    aggregate_type varchar(255) not null,
    claim_token varchar(255),
    event_type varchar(255) not null,
    status varchar(255) not null check (status in ('NEW','PROCESSING','PUBLISHED','FAILED')),
    headers oid not null,
    last_error oid,
    payload oid not null,
    primary key (id)
);

CREATE TABLE inventory_reservation (
    quantity integer not null,
    created_at timestamp(6) not null,
    expires_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    idempotency_key varchar(255),
    inventory_item_uuid varchar(255) not null,
    order_id varchar(255) not null,
    order_line_id varchar(255) not null,
    status varchar(255) not null check (status in ('ACTIVE','RELEASED','FULFILLED','EXPIRED','CANCELLED')),
    uuid varchar(255) not null unique,
    primary key (id),
    constraint idx_inventory_reservation_idempotency unique (idempotency_key)
);

CREATE TABLE location (
    active boolean not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    city varchar(255),
    code varchar(255) not null unique,
    country varchar(255),
    merchant_id varchar(255) not null,
    name varchar(255) not null,
    postal_code varchar(255),
    state varchar(255),
    street varchar(255),
    street2 varchar(255),
    type varchar(255) not null check (type in ('WAREHOUSE','STORE')),
    uuid varchar(255) not null unique,
    primary key (id)
);

CREATE TABLE location_sales_channels (
    location_id bigint not null,
    sales_channel_id varchar(255) not null,
    primary key (location_id, sales_channel_id)
);

CREATE TABLE product_variant_view (
    manage_inventory boolean not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    product_name varchar(255),
    product_uuid varchar(255) not null,
    sku varchar(255) not null,
    status varchar(255) not null,
    variant_uuid varchar(255) not null unique,
    primary key (id)
);

CREATE TABLE security_manifest_publication (
    security_revision integer not null,
