    lease_until timestamp(6) with time zone,
    version bigint not null,
    content_digest varchar(255) not null,
    module_key varchar(255) not null,
    primary key (module_key)
);

CREATE TABLE stock_movement (
    on_hand_after integer not null,
    on_hand_before integer not null,
    quantity integer not null,
    quantity_after integer not null,
    quantity_before integer not null,
    reserved_after integer not null,
    reserved_before integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    created_by varchar(255),
    inventory_item_uuid varchar(255) not null,
    reference_id varchar(255),
    type varchar(255) not null check (type in ('PURCHASE_ORDER_RECEIPT','CUSTOMER_RETURN','TRANSFER_IN','INITIAL_STOCK','SALE','TRANSFER_OUT','RETURN_TO_VENDOR','WRITE_OFF','CYCLE_COUNT_ADJUSTMENT','DAMAGE_ADJUSTMENT','SHRINKAGE','IN_TRANSIT_ANNOUNCE','IN_TRANSIT_RECEIPT','RESERVATION','RESERVATION_RELEASE')),
    uuid varchar(255) not null unique,
    primary key (id)
);

CREATE TABLE zone (
    active boolean not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    code varchar(255) not null,
    location_id varchar(255) not null,
    name varchar(255) not null,
    type varchar(255) not null check (type in ('PICKING','STORAGE','STAGING','RETURNS','DAMAGED','RECEIVING')),
    uuid varchar(255) not null unique,
    primary key (id),
    constraint idx_zone_code_location unique (code, location_id)
