-- Initial PostgreSQL schema for the storefrontquery module.
-- Create-only migration; no seed data.
CREATE TABLE buyable_offer (
    amount numeric(19, 4),
    available_qty integer not null,
    buyable boolean not null,
    channel_enabled boolean not null,
    id bigint generated by default as identity,
    published boolean not null,
    untracked boolean not null,
    updated_at timestamp(6) with time zone not null,
    currency varchar(255),
    media varchar(255),
    product_id varchar(255),
    product_status varchar(255),
    sales_channel_id varchar(255) not null,
    seller_id varchar(255),
    sku varchar(255),
    slug varchar(255),
    title varchar(255),
    variant_id varchar(255) not null,
    primary key (id),
    constraint uq_buyable_offer_channel_variant unique (sales_channel_id, variant_id)
);

CREATE INDEX idx_buyable_offer_channel_buyable ON buyable_offer (sales_channel_id, buyable);
CREATE INDEX idx_buyable_offer_slug ON buyable_offer (sales_channel_id, slug);
CREATE INDEX idx_buyable_offer_sku ON buyable_offer (sku);
