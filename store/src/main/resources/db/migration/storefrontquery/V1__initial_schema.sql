CREATE TABLE discovery_product (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    sales_channel_id varchar(255) not null,
    product_id varchar(255) not null,
    merchant_id varchar(255),
    category_id varchar(255),
    title varchar(255),
    slug varchar(255),
    description text,
    thumbnail varchar(2048),
    product_status varchar(64),
    published boolean not null,
    channel_enabled boolean not null,
    has_stock boolean not null,
    options jsonb not null default '[]'::jsonb,
    variants jsonb not null default '[]'::jsonb,
    updated_at timestamp(6) with time zone not null,
    constraint uq_discovery_product_channel_product unique (sales_channel_id, product_id),
    constraint uq_discovery_product_channel_slug unique (sales_channel_id, slug)
);

CREATE INDEX idx_discovery_product_channel_published
    ON discovery_product (sales_channel_id, published, channel_enabled, product_status);
CREATE INDEX idx_discovery_product_slug ON discovery_product (sales_channel_id, slug);
CREATE INDEX idx_discovery_product_category ON discovery_product (sales_channel_id, category_id);

CREATE TABLE discovery_product_variant (
    id bigint generated by default as identity primary key,
    discovery_product_id bigint not null references discovery_product(id) on delete cascade,
    variant_id varchar(255) not null,
    sku varchar(255),
    variant_status varchar(64) not null,
    constraint uq_discovery_product_variant unique (discovery_product_id, variant_id)
);

CREATE INDEX idx_discovery_variant_id ON discovery_product_variant (variant_id);
CREATE INDEX idx_discovery_variant_sku ON discovery_product_variant (sku);
CREATE INDEX idx_discovery_variant_product_status ON discovery_product_variant (discovery_product_id, variant_status);

CREATE TABLE discovery_rebuild_run (
    run_id varchar(255) primary key,
    started_at timestamp(6) with time zone not null,
    stage varchar(32) not null,
    last_product_id varchar(255),
    last_sales_channel_id varchar(255),
    processed_count bigint not null default 0,
    invalidated_count bigint not null default 0,
    version bigint not null default 0,
    constraint ck_discovery_rebuild_stage check (stage in ('PUBLICATIONS', 'EXISTING_PROJECTIONS', 'COMPLETED'))
);

CREATE UNIQUE INDEX uq_discovery_rebuild_unfinished
    ON discovery_rebuild_run ((true)) WHERE stage <> 'COMPLETED';
